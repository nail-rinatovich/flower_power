from decimal import Decimal
from django.contrib import messages
from django.db.models import Q
from django.shortcuts import get_object_or_404, redirect, render
from django.urls import reverse
from django.views.decorators.http import require_POST
from .cart import Cart
from .models import Category, Product


def catalog(request):
    products = Product.objects.filter(available=True).select_related('category')
    category = request.GET.get('category', '')
    query = request.GET.get('q', '').strip()[:100]
    sort = request.GET.get('sort', '')
    if category:
        products = products.filter(category__slug=category)
    if query:
        products = products.filter(Q(name__icontains=query) | Q(description__icontains=query))
    orders = {'price': 'price', '-price': '-price', 'name': 'name'}
    products = products.order_by(orders.get(sort, '-created_at'))
    return render(request, 'shop/catalog.html', {
        'products': products, 'categories': Category.objects.all(), 'selected_category': category,
        'query': query, 'sort': sort,
    })

def product(request, slug):
    item = get_object_or_404(Product, slug=slug, available=True)
    return render(request, 'shop/product.html', {'product': item})

def cart(request):
    items = Cart(request).items()
    return render(request, 'shop/cart.html', {
        'items': items, 'total': sum((item['total'] for item in items), Decimal('0')),
    })

@require_POST
def add_to_cart(request, pk):
    item = get_object_or_404(Product, pk=pk, available=True)
    basket = Cart(request)
    basket.add(item)
    messages.success(request, f'«{item.name}» добавлен в корзину')
    # Only allow destinations generated by our own application.
    destination = request.POST.get('destination')
    if destination == 'product':
        return redirect(item)
    if destination == 'catalog':
        return redirect(reverse('shop:catalog') + '#catalog')
    return redirect('shop:cart')

@require_POST
def update_cart(request, pk):
    item = get_object_or_404(Product, pk=pk)
    try:
        quantity = int(request.POST.get('quantity', '1'))
    except (ValueError, TypeError):
        messages.error(request, 'Введите количество от 0 до 99.')
        return redirect('shop:cart')
    if not 0 <= quantity <= 99:
        messages.error(request, 'Количество должно быть от 0 до 99.')
    else:
        Cart(request).set(item, quantity)
    return redirect('shop:cart')
